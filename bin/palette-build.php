<?php
/**
 * Elite Nail Studio palette build + contrast gate.
 *
 * Reads bin/palette-sources.json (the EDS palette library: name, swatches and
 * the ink / depth / metal / mist / paper source map), derives the Nail Studio
 * slots for every palette, gates every tone with WCAG 2.2 AA pairs and writes
 * inc/palette-registry.php (the only runtime registry; a plain PHP array).
 *
 * Usage:  php bin/palette-build.php          write the registry, list results
 *         php bin/palette-build.php --check  exit 1 if the registry is stale or a palette fails
 *
 * Derivation (every push is the smallest step that passes, and is recorded):
 *   espresso   = ink, darkened only if it is not a dark base (lum <= .04)       dark sections, headings, buttons
 *   ivory      = paper, lightened only if it is not a light base (lum >= .78)   page, text on dark
 *   porcelain  = ivory 60% toward white                                         cards, forms
 *   nude       = mist when light enough, else a step from paper; holds espresso image wells, badges
 *   linen      = ivory 45% toward nude                                          alternate light sections
 *   cocoa      = depth, darkened until it reads on every light surface         body / muted text
 *   taupe      = dimmest step from cocoa toward ivory that still reads          labels, meta
 *   rose       = metal, never altered                                           accent fill (button wash, badge)
 *   on-rose    = espresso or ivory, whichever reads on rose (pushed if neither) label on the accent
 *   rose-ink   = metal darkened until it reads on light surfaces                eyebrows, emphasis, links
 *   rose-glow  = metal lightened until it reads on dark surfaces                emphasis, links on dark
 *   champagne  = metal 35% toward paper, lightened to read on dark surfaces     eyebrows on dark, stars, details
 *   champagne-ink = champagne darkened until it reads on light surfaces         focus ring on light
 *   rose-card, rose-muted = card and muted text for Accent sections (rose fill)
 * Atelier is `fixed`: its eleven slots are the approved Maison Élise colours, byte
 * for byte; only the helper slots (on-rose, rose-glow, rose-card, rose-muted) are derived.
 */

require __DIR__ . '/palette-lib.php';

/* Build ------------------------------------------------------------------ */

/** Five card swatches: the library colours, completed from the resolved source map, then from derived slots. */
function ensb_swatches( array $p, array $slots ): array {
	$colors = array_map( 'strtolower', $p['colors'] );
	$extra = array_map( static fn( $role ) => ensb_source( $p['map'][ $role ] ), [ 'ink', 'depth', 'metal', 'mist', 'paper' ] );
	foreach ( array_merge( $extra, [ $slots['champagne'], $slots['nude'], $slots['rose-ink'] ] ) as $hex ) {
		if ( count( $colors ) < 5 && ! in_array( $hex, $colors, true ) ) {
			$colors[] = $hex;
		}
	}
	return $colors;
}

$ensb_sources  = json_decode( (string) file_get_contents( __DIR__ . '/palette-sources.json' ), true );
$ensb_registry = [];
$ensb_report   = [];
$ensb_failed   = 0;

foreach ( $ensb_sources['palettes'] as $ensb_slug => $ensb_p ) {
	$ensb_fixed = 'atelier' === $ensb_slug;
	if ( $ensb_fixed ) {
		$ensb_notes = [];
		$ensb_slots = ens_palette_atelier();
		$ensb_slots += ensb_helpers( $ensb_slots, static function ( $slot, $push, $what ) use ( &$ensb_notes ) {
			if ( 0.0 !== (float) $push ) {
				$ensb_notes[] = "{$slot}: {$what}";
			}
		} );
		$ensb_d = [ 'slots' => $ensb_slots, 'notes' => array_merge( [ 'fixed: the approved Maison Élise colours' ], $ensb_notes ) ];
	} else {
		$ensb_d = ensb_derive( $ensb_p['map'] );
	}
	$ensb_slots  = $ensb_d['slots'];
	$ensb_fail   = array_merge(
		ensb_gate_tone( $ensb_slots, ens_palette_accent_sources( true ), 'light' ),
		ensb_gate_tone( $ensb_slots, ens_palette_accent_sources( true ), 'dark' )
	);
	$ensb_accent = ! ensb_gate_tone( $ensb_slots, ens_palette_accent_sources( true ), 'accent' );
	$ensb_ok     = ! $ensb_fail;
	$ensb_failed += $ensb_ok ? 0 : 1;

	$ensb_registry[ $ensb_slug ] = [
		'name'       => $ensb_p['name'],
		'default'    => $ensb_fixed,
		'selectable' => $ensb_ok,
		'colors'     => ensb_swatches( $ensb_p, $ensb_slots ),
		'slots'      => $ensb_slots,
		'sections'   => [
			'dark'   => $ensb_ok,
			'light'  => $ensb_ok,
			'accent' => $ensb_ok && $ensb_accent,
		],
		'notes'      => array_merge( $ensb_d['notes'], $ensb_fail ),
	];
	$ensb_report[] = sprintf( '%-4s %-24s accent:%-3s %s', $ensb_ok ? 'ok' : 'FAIL', $ensb_p['name'], $ensb_registry[ $ensb_slug ]['sections']['accent'] ? 'yes' : 'no', $ensb_ok ? '' : implode( '; ', array_slice( $ensb_fail, 0, 3 ) ) );
}

$ensb_php = "<?php\n/**\n * GENERATED by bin/palette-build.php from bin/palette-sources.json. Do not edit by hand.\n */\n\nreturn " . var_export( $ensb_registry, true ) . ";\n";
$ensb_php = str_replace( "\r\n", "\n", $ensb_php );
$ensb_out = __DIR__ . '/../inc/palette-registry.php';

if ( in_array( '--check', $argv, true ) ) {
	$ensb_stale = ! is_file( $ensb_out ) || str_replace( "\r\n", "\n", (string) file_get_contents( $ensb_out ) ) !== $ensb_php;
	echo implode( "\n", $ensb_report ), "\n";
	echo $ensb_stale ? "\nRegistry is stale: run php bin/palette-build.php\n" : "\nRegistry up to date.\n";
	exit( $ensb_stale || $ensb_failed ? 1 : 0 );
}

file_put_contents( $ensb_out, $ensb_php );
echo implode( "\n", $ensb_report ), "\n\n";
printf( "%d palettes, %d offered, %d with Accent sections. Wrote inc/palette-registry.php\n", count( $ensb_registry ), count( array_filter( $ensb_registry, static fn( $r ) => $r['selectable'] ) ), count( array_filter( $ensb_registry, static fn( $r ) => $r['sections']['accent'] ) ) );
